"""Build fixture/answer_key/events.json: real, calendar and planted changes with expected outcomes.

Real changes come from OpenCaseLaw tool output only:
- statute amendments (T1, and T2 for records decided before adoption):
  current get_law text compared with the text copied into the record;
  dates parsed from the footnote clause ("... vom <adopted>, in Kraft seit
  <in force> (AS ...)") or from "Act in force: ... (repealed)";
- citing federal decisions (T3, logged): find_citations, a sample of up
  to T3_PER_DECISION per relied-on decision;
- new leading decisions (T5): get_regeste and cite, chosen by hand.
Calendar events (T12 commitment dates, T14 review dates) are derived
from the records. Planted events come from src/planted.py.

Expected outcomes for real changes that touch a relied-on paragraph are
judgements listed in JUDGE below. Every event is review.status "draft".
"""
from __future__ import annotations

import datetime as dt
import json
import re
from pathlib import Path

from . import lawtext, sources
from .build import FIXTURE, RECORDS_DIR

KEY_DIR = FIXTURE / "answer_key"
REPLAY_START, REPLAY_END = "2020-03-26", "2026-10-01"
T3_PER_DECISION = 6
REVIEW = {"status": "draft", "prepared_by": "generated by Claude (claude-opus-5-5) for v0.1",
          "reviewed_by": None, "reviewed_at": None}

MONTHS = {"Jan": 1, "Febr": 2, "Feb": 2, "März": 3, "April": 4, "Apr": 4, "Mai": 5, "Juni": 6, "Juli": 7,
          "Aug": 8, "Sept": 9, "Sep": 9, "Okt": 10, "Nov": 11, "Dez": 12}
_FN_CLAUSE = re.compile(r"vom (\d{1,2}\. [A-Za-zä]+\.? \d{4})(?:(?!vom ).)*?in Kraft seit (\d{1,2}\. [A-Za-zä]+\.? \d{4}) \([^)]+\)")

# Judgement for real amendments that change a relied-on paragraph: (record, basis) -> stage -> outcome.
JUDGE = {
    ("rec_01_dividend_fy2019", "l2"): {"*": ("log", "Numbers 5 to 8 inserted; the general meeting still decides on the dividend. Dividend paid in 2020.")},
    ("rec_02_service_gmbh_subordination_2020", "l1"): {
        "adopted": ("push", "medium", "The over-indebtedness rule relied on is replaced; under the new text a subordination must also cover interest, which the 2020 subordination does not (f2)."),
        "in_force": ("push", "high", "Rule relied on replaced in force; the subordination does not cover interest as now required.")},
    ("rec_02_service_gmbh_subordination_2020", "l2"): {"*": ("log", "Re-worded; company-law rules still apply to a GmbH.")},
    ("rec_08_dividend_fy2021", "l2"): {"*": ("log", "Number 4 on listed companies' compensation report added; Sernfeld is unlisted, dividend paid.")},
    ("rec_09_cv_screening_pilot", "l1"): {"*": ("log", "Reference to the data protection act updated; the pilot ended on 31 July 2023.")},
    ("rec_11_hegi_land_sale", "l2"): {"*": ("push", "high", "Restitution rule re-worded before the sale completes (31 March 2023); the economic-situation criterion is gone, so restitution becomes easier.")},
}
ACT_REPEAL_JUDGE = {
    ("rec_07_sernsense_predictive_maintenance", "l1"): ("push", "high", "Old data protection act replaced while SernSense runs; transfer to the USA and processor rules now follow the new act."),
    ("rec_07_sernsense_predictive_maintenance", "l2"): ("push", "high", "As l1."),
    ("rec_07_sernsense_predictive_maintenance", "l3"): ("push", "high", "As l1."),
    ("rec_09_cv_screening_pilot", "l3"): ("log", "The pilot ended on 31 July 2023, before the new act entered into force."),
    ("rec_05_md200_release_ch_eu", "l1"): ("log", "Repeal anticipated: the record already relies on the new ordinance from 26 May 2021 (l2)."),
}
T5_REAL = [
    {"decision_id": "bge_BGE_150_III_315",
     "expected": [("rec_02_service_gmbh_subordination_2020", "push", "medium", ["l1", "f2"],
                   "Leading decision requires the subordination to cover interest; the 2020 subordination does not."),
                  ("rec_13_service_gmbh_capital_loss_2023", "log", "low", ["f2"],
                   "Capital-loss record; the GmbH was not over-indebted in the 2022 accounts.")]},
    {"decision_id": "bge_BGE_151_III_440",
     "expected": [("rec_02_service_gmbh_subordination_2020", "log", "low", ["f2"],
                   "Concerns collocation of loans made before over-indebtedness; no effect on the subordination relied on."),
                  ("rec_13_service_gmbh_capital_loss_2023", "log", "low", ["f2"], "As for rec_02.")]},
]


def de_date(s: str) -> str:
    """'1. Jan. 2023' -> '2023-01-01'."""
    d, m, y = s.split()
    return dt.date(int(y), MONTHS[m.rstrip(".")], int(d.rstrip("."))).isoformat()


def _norm(s: str | None) -> str:
    s = re.sub(r"-\s*\n\s*", "", s or "")
    s = re.sub(r"\b\d{3,4}(?=\s|$)", "", s)  # PDF footnote markers
    return re.sub(r"\s+", " ", s).strip()


def _exp(rec, action, sev, basis, why):
    return {"record_id": rec, "action": action, "severity": sev, "basis_ids": basis, "rationale": why}


def load_records() -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(RECORDS_DIR.glob("*.json"))]


def _para_changed(entry: dict, cur: dict) -> bool:
    para = entry["paragraph"]
    now = cur["body"] if para is None else cur["paragraphs"].get(para)
    if now is None:
        return True
    if entry["text"] is not None:
        return _norm(now) != _norm(entry["text"])
    old = lawtext.parse(sources.text_of(sources.load(entry["source_snapshot"])))
    probe = re.sub(r"^\S+ ", "", _norm(now)) if para else _norm(now)
    return probe[:120] not in _norm(old["body"])


def real_statute_events(records: list[dict], refresh: bool) -> list[dict]:
    events = []
    groups: dict[tuple, list] = {}
    for r in records:
        for e in r["basis"]["law"]:
            if e["kind"] == "statute":
                old = lawtext.parse(sources.text_of(sources.load(e["source_snapshot"])))
                if old["repealed"]:
                    groups.setdefault(("repeal", e["sr_number"], e["act_title"]), []).append((r, e, old))
                else:
                    groups.setdefault(("article", e["law"], e["article"]), []).append((r, e, None))
    for gk, members in groups.items():
        if gk[0] == "repeal":
            _, sr, title = gk
            old = members[0][2]
            repealed_on = re.search(r"– (\d{4}-\d{2}-\d{2}) \(repealed\)", old["act_in_force"]).group(1)
            exp = []
            for r, e, _ in members:
                if r["decided_at"] < repealed_on:
                    a = ACT_REPEAL_JUDGE[(r["id"], e["id"])]
                    exp.append(_exp(r["id"], a[0], a[1] if a[0] == "push" else "low", [e["id"]], a[-1]))
            events.append({"origin": "real", "trigger": "T1", "published_at": repealed_on,
                           "change": {"kind": "act_repealed", "law": members[0][1]["law"], "sr_number": sr, "act_title": title,
                                      "act_in_force": old["act_in_force"], "articles": sorted({e["article"] for _, e, _ in members}),
                                      "source_snapshots": sorted({e["source_snapshot"] for _, e, _ in members})},
                           "expected": _merge(exp)})
            continue
        _, law, article = gk
        k, snap = sources.fetch("get_law", {"abbreviation": law, "article": article}, refresh=refresh)
        cur = lawtext.parse(sources.text_of(snap))
        clauses = [(m.group(0), de_date(m.group(1)), de_date(m.group(2)))
                   for fn in cur["footnotes"] for m in _FN_CLAUSE.finditer(fn)]
        first = min(r["decided_at"] for r, _, _ in members)
        amendments = sorted({c for c in clauses if first < c[2] <= REPLAY_END}, key=lambda c: c[2])
        for clause, adopted, in_force in amendments:
            for stage, date in (("adopted", adopted), ("in_force", in_force)):
                exp = []
                for r, e, _ in members:
                    if not r["decided_at"] < date or (stage == "adopted" and r["decided_at"] >= adopted):
                        continue
                    if _para_changed(e, cur):
                        j = JUDGE[(r["id"], e["id"])]
                        a = j.get(stage) or j["*"]
                        exp.append(_exp(r["id"], a[0], a[1] if a[0] == "push" else "low", [e["id"]], a[-1]))
                    else:
                        exp.append(_exp(r["id"], "log", "low", [e["id"]],
                                        "The article was amended, but the relied-on paragraph is unchanged."))
                if not exp:
                    continue
                paras_now = {p: cur["paragraphs"][p] for p in sorted({e["paragraph"] for _, e, _ in members if e["paragraph"]})
                             if p in cur["paragraphs"]}
                events.append({"origin": "real", "trigger": "T2" if stage == "adopted" else "T1", "published_at": date,
                               "change": {"kind": "statute_amendment", "stage": stage, "law": law, "sr_number": cur["sr_number"],
                                          "article": article, "article_label": cur["article_label"],
                                          "adopted_at": adopted, "in_force_at": in_force, "footnote": clause,
                                          "current_text": cur["body"] if not paras_now else None,
                                          "current_paragraphs": paras_now or None,
                                          "source_url": cur["source_url"], "source_snapshot": k},
                               "expected": _merge(exp)})
    return events


def _merge(exp: list[dict]) -> list[dict]:
    """One expectation per record: the strongest action, basis ids united."""
    rank = {"push": 2, "log": 1, "none": 0}
    sev_rank = {"high": 2, "medium": 1, "low": 0, None: -1}
    out: dict[str, dict] = {}
    for x in exp:
        cur = out.get(x["record_id"])
        if cur is None:
            out[x["record_id"]] = dict(x, basis_ids=list(x["basis_ids"]))
            continue
        ids = sorted(set(cur["basis_ids"]) | set(x["basis_ids"]))
        if (rank[x["action"]], sev_rank[x["severity"]]) > (rank[cur["action"]], sev_rank[cur["severity"]]):
            out[x["record_id"]] = dict(x)
        out[x["record_id"]]["basis_ids"] = ids
    return list(out.values())


def real_decision_events(records: list[dict], refresh: bool) -> list[dict]:
    relying: dict[str, list] = {}
    for r in records:
        for e in r["basis"]["law"]:
            if e["kind"] == "decision":
                relying.setdefault(e["decision_id"], []).append((r, e))
    events = []
    for did, members in sorted(relying.items()):
        first = min(r["decided_at"] for r, _ in members)
        rows, off = [], 0
        while True:
            k, snap = sources.fetch("find_citations", {"decision_id": did, "direction": "incoming", "limit": 200,
                                                       "min_confidence": 0.8, "offset": off}, refresh=refresh)
            md = sources.text_of(snap)
            rows += [(m.group(1), m.group(2), m.group(3), m.group(4), k) for m in re.finditer(
                r"^\d+\. \[([^\]]+)\]\((\S+)\) \((\d{4}-\d{2}-\d{2})\) \[(\w+)\]", md, re.M)]
            nxt = re.search(r"next_offset=(\d+)", md)
            if not nxt:
                break
            off = int(nxt.group(1))
        fed = sorted({r for r in rows if r[3] in ("bger", "bge") and first < r[2] <= REPLAY_END}, key=lambda r: r[2])
        if len(fed) > T3_PER_DECISION:
            step = (len(fed) - 1) / (T3_PER_DECISION - 1)
            fed = [fed[round(i * step)] for i in range(T3_PER_DECISION)]
        for label, url, date, court, k in fed:
            exp = [_exp(r["id"], "log", "low", [e["id"]], "Later federal decision citing a relied-on decision; not classified as qualifying in v0.1.")
                   for r, e in members if r["decided_at"] < date]
            events.append({"origin": "real", "trigger": "T3", "published_at": date,
                           "change": {"kind": "court_decision", "relation": "cites", "label": label, "url": url,
                                      "court": court, "decision_date": date, "cites": did, "source_snapshot": k},
                           "expected": _merge(exp)})
    for t in T5_REAL:
        ck, csnap = sources.fetch("cite", {"reference": t["decision_id"]}, refresh=refresh)
        rk, rsnap = sources.fetch("get_regeste", {"decision_id": t["decision_id"]}, refresh=refresh)
        reg = rsnap["result"]["regeste"].split("\nRegeste\n")[0].strip()
        date = csnap["result"]["decision_date"]
        events.append({"origin": "real", "trigger": "T5", "published_at": date,
                       "change": {"kind": "court_decision", "relation": "new_leading", "decision_id": t["decision_id"],
                                  "citation": csnap["result"]["citation_string"], "decision_date": date,
                                  "regeste": reg, "source_snapshots": [ck, rk]},
                       "expected": [_exp(*x[:2], x[2], x[3], x[4]) for x in t["expected"]]})
    return events


def calendar_events(records: list[dict]) -> list[dict]:
    events = []
    for r in records:
        rd = r["review"]["date"]
        if rd <= REPLAY_END:
            events.append({"id": f"cal:{r['id']}:record:T14", "origin": "calendar", "trigger": "T14", "published_at": rd,
                           "change": {"kind": "review_date", "record_id": r["id"], "date": rd},
                           "expected": [_exp(r["id"], "push", "medium", ["record"], "Review date reached.")]})
        for c in r["basis"]["commitments"]:
            due = (dt.date.fromisoformat(c["test_date"]) - dt.timedelta(days=14)).isoformat()
            if r["decided_at"] <= due <= REPLAY_END:
                events.append({"id": f"cal:{r['id']}:{c['id']}:T12", "origin": "calendar", "trigger": "T12", "published_at": due,
                               "change": {"kind": "commitment_date", "record_id": r["id"], "basis_id": c["id"], "test_date": c["test_date"]},
                               "expected": [_exp(r["id"], "push", "medium", [c["id"]], "Commitment test date in 14 days.")]})
    return events


def planted_events(records: list[dict]) -> list[dict]:
    from .src.planted import PLANTED
    by_id = {r["id"]: r for r in records}
    out, errors = [], []
    for p in PLANTED:
        ev = json.loads(json.dumps(p))
        ch = ev["change"]
        if ch["kind"] == "statute_amendment" and "target" in ch:
            rec, bid = ch.pop("target")
            e = next(x for x in by_id[rec]["basis"]["law"] if x["id"] == bid)
            for f in ("law", "sr_number", "act_title", "jurisdiction", "article", "article_label", "source_url"):
                ch[f] = e.get(f)
            ch["paragraph"] = ch.get("paragraph") if ch.get("paragraph") is not None else e.get("paragraph")
            ch["copied_from"] = {"record_id": rec, "basis_id": bid, "source_snapshot": e["source_snapshot"]}
        elif ch["kind"] == "statute_amendment" and "snapshot" in ch:
            k = ch.pop("snapshot")
            p_ = lawtext.parse(sources.text_of(sources.load(k)))
            for f in ("law", "sr_number", "act_title", "jurisdiction", "article", "article_label", "source_url"):
                ch[f] = p_[f]
            ch["copied_from"] = {"source_snapshot": k}
        ev["origin"] = "planted"
        # A record not yet decided when the change is published cannot be flagged.
        for x in ev["expected"]:
            if by_id[x["record_id"]]["decided_at"] > ev["published_at"] and x["action"] != "none":
                errors.append(f"planted event on {ev['published_at']} expects {x['action']} for later record {x['record_id']}")
        out.append(ev)
    if errors:
        raise ValueError("\n".join(errors))
    return out


def build_answer_key(refresh: bool = False) -> list[dict]:
    records = load_records()
    events = real_statute_events(records, refresh) + real_decision_events(records, refresh) + \
        calendar_events(records) + planted_events(records)
    events.sort(key=lambda e: (e["published_at"], e["origin"], json.dumps(e["change"], sort_keys=True, ensure_ascii=False)))
    n = 0
    for e in events:
        if "id" not in e:
            n += 1
            e["id"] = f"ev_{n:04d}"
        e["review"] = dict(REVIEW)
    ordered = [{k: e[k] for k in ("id", "origin", "trigger", "published_at", "change", "injection", "expected", "review") if k in e}
               for e in events]
    KEY_DIR.mkdir(parents=True, exist_ok=True)
    (KEY_DIR / "events.json").write_text(json.dumps({
        "schema_version": "0.1",
        "replay": {"start": REPLAY_START, "end": REPLAY_END},
        "notice": "Answer key prepared before any agent run. Every expected outcome is a draft until a named lawyer reviews it. "
                  "Texts marked SYNTHETIC are not law.",
        "events": ordered}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    from collections import Counter
    c = Counter((e["origin"], e["trigger"]) for e in ordered)
    acts = Counter(x["action"] for e in ordered for x in e["expected"])
    print(f"{len(ordered)} events; {dict(sorted(c.items()))}; expected actions {dict(acts)}")
    return ordered
